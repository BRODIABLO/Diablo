inline constexpr std::uint32_t SerializedWordsPerCell = 3U;
inline constexpr std::uint32_t SerializedBytesPerWord = 2U;
inline constexpr std::uint32_t MaximumSerializedWordCount =
    (std::numeric_limits<std::uint32_t>::max)()
    / SerializedBytesPerWord;

struct ByteCountResult final {
    bool representable{};
    std::uint32_t byteCount{};
};

[[nodiscard]] constexpr auto ComputeSerializedByteCount(
        std::uint32_t wordCount) noexcept -> ByteCountResult {
    if (wordCount > MaximumSerializedWordCount) return {};
    return {
        true,
        static_cast<std::uint32_t>(wordCount * SerializedBytesPerWord),
    };
}

[[nodiscard]] constexpr auto ComputeSerializedCellByteCount(
        std::uint32_t emittedCellCount) noexcept -> ByteCountResult {
    if (emittedCellCount
            > MaximumSerializedWordCount / SerializedWordsPerCell) {
        return {};
    }
    return ComputeSerializedByteCount(
        emittedCellCount * SerializedWordsPerCell);
}

