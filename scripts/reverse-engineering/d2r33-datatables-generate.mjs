#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  defaultAtlasDirectory,
  defaultCatalogPath,
  repositoryRoot,
  validateCatalog,
} from './d2r33-datatables-atlas.mjs';

export const defaultGeneratedDirectory = path.join(defaultAtlasDirectory, 'generated');

const outputNames = Object.freeze({
  cppHeader: 'd2r33_datatables_atlas.hpp',
  ghidraHeader: 'd2r33_datatables_ghidra.h',
  witness: 'd2r33_datatables_atlas_witness.cpp',
  manifest: 'manifest.json',
});

const typeSizes = Object.freeze({
  int8_t: 1,
  uint8_t: 1,
  int16_t: 2,
  uint16_t: 2,
  int32_t: 4,
  uint32_t: 4,
  int64_t: 8,
  uint64_t: 8,
});

function sha256Hex(value) {
  return crypto.createHash('sha256').update(value).digest('hex').toUpperCase();
}

function parseHex(value) {
  return Number.parseInt(value.slice(2), 16);
}

function formatHex(value) {
  return `0x${value.toString(16).toUpperCase()}`;
}

function pascalCase(value) {
  return value
    .split(/[^A-Za-z0-9]+/u)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('');
}

function camelCase(value) {
  const pascal = pascalCase(value);
  return `${pascal[0].toLowerCase()}${pascal.slice(1)}`;
}

function macroCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/gu, '$1_$2')
    .replace(/[^A-Za-z0-9]+/gu, '_')
    .toUpperCase();
}

function paddingName(offset) {
  return `unknown${offset.toString(16).toUpperCase().padStart(4, '0')}`;
}

function evidenceComment(entry) {
  return `${entry.status}; evidence: ${entry.evidenceIds.join(', ')}`;
}

function collectSlots(catalog) {
  const slots = [];
  for (const table of catalog.tables) {
    for (const kind of ['records', 'count', 'linker']) {
      const fact = table[kind];
      if (!fact || fact.status === 'unknown') continue;
      slots.push({
        table,
        kind,
        offset: parseHex(fact.value),
        size: 8,
        status: fact.status,
        evidenceIds: fact.evidenceIds,
        name: `${camelCase(table.id)}${pascalCase(kind)}`,
      });
    }
  }
  return slots.sort((left, right) => left.offset - right.offset || left.name.localeCompare(right.name));
}

function collectRecordMembers(table) {
  return table.recordFields
    .map((field) => ({
      ...field,
      memberName: camelCase(field.name),
      numericOffset: parseHex(field.offset),
    }))
    .sort((left, right) => left.numericOffset - right.numericOffset || left.memberName.localeCompare(right.memberName));
}

function renderMembers({ entries, totalSize, typeFor, indent = '  ' }) {
  const lines = [];
  let cursor = 0;
  for (const entry of entries) {
    if (entry.offset > cursor) {
      const length = entry.offset - cursor;
      lines.push(`${indent}${typeFor('padding')} ${paddingName(cursor)}[${formatHex(length)}]; // Unknown bytes ${formatHex(cursor)}..${formatHex(entry.offset - 1)}.`);
    }
    lines.push(`${indent}${typeFor(entry.type)} ${entry.name}; // +${formatHex(entry.offset)} ${evidenceComment(entry)}.`);
    cursor = entry.offset + entry.size;
  }
  if (cursor < totalSize) {
    lines.push(`${indent}${typeFor('padding')} ${paddingName(cursor)}[${formatHex(totalSize - cursor)}]; // Unknown bytes ${formatHex(cursor)}..${formatHex(totalSize - 1)}.`);
  }
  return lines;
}

function cppType(type) {
  if (type === 'padding') return 'std::uint8_t';
  if (!Object.hasOwn(typeSizes, type)) throw new Error(`unsupported C++ field type: ${type}`);
  return `std::${type}`;
}

function cType(type) {
  if (type === 'padding') return 'uint8_t';
  if (!Object.hasOwn(typeSizes, type)) throw new Error(`unsupported Ghidra field type: ${type}`);
  return type;
}

function renderCppHeader(catalog, catalogHash) {
  const lines = [
    '// Generated by scripts/reverse-engineering/d2r33-datatables-generate.mjs.',
    '// Do not edit by hand. Unknown bytes are deliberate; this is not a complete SDK layout.',
    `// Source catalog SHA-256: ${catalogHash}`,
    `// Runtime tested by the catalog: D2R.exe ${catalog.targetRuntime.version}; covered builds: ${catalog.corpus.coveredBuilds.map((entry) => entry.build).join(', ')}.`,
    '#pragma once',
    '',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    'namespace ruffneckk::d2r33::datatables {',
    '',
    `inline constexpr std::uintptr_t kDataTablesAccessorRva = ${catalog.dataTables.accessorRva}U;`,
    `inline constexpr std::uint32_t kDataTablesContextCount = ${catalog.dataTables.contextCount}U;`,
    `inline constexpr std::size_t kDataTablesGlobalEntryStride = ${catalog.dataTables.globalEntryStride}U;`,
    '',
    '#pragma pack(push, 1)',
  ];

  for (const table of catalog.tables) {
    const structName = `${pascalCase(table.displayName)}RecordView`;
    const recordSize = parseHex(table.recordSize.value);
    const members = collectRecordMembers(table).map((field) => ({
      offset: field.numericOffset,
      size: field.size,
      type: field.type,
      name: field.memberName,
      status: field.status,
      evidenceIds: field.evidenceIds,
    }));
    lines.push('', `struct ${structName} {`);
    lines.push(...renderMembers({ entries: members, totalSize: recordSize, typeFor: cppType }));
    lines.push('};');
  }

  const slots = collectSlots(catalog);
  const prefixSize = slots.at(-1).offset + slots.at(-1).size;
  const slotMembers = slots.map((slot) => ({
    offset: slot.offset,
    size: slot.size,
    type: slot.kind === 'count' ? 'uint64_t' : 'uintptr_t',
    name: slot.name,
    status: slot.status,
    evidenceIds: slot.evidenceIds,
  }));
  const cppSlotType = (type) => {
    if (type === 'uintptr_t') return 'std::uintptr_t';
    return cppType(type);
  };
  lines.push(
    '',
    '// Known prefix only: DataTables continues beyond the last governed slot.',
    'struct DataTablesKnownPrefixView {',
    ...renderMembers({ entries: slotMembers, totalSize: prefixSize, typeFor: cppSlotType }),
    '};',
    '',
    '#pragma pack(pop)',
    '',
    'static_assert(sizeof(std::uintptr_t) == 8, "D2R DataTables requires an x64 target");',
  );

  for (const table of catalog.tables) {
    const structName = `${pascalCase(table.displayName)}RecordView`;
    lines.push(`static_assert(sizeof(${structName}) == ${table.recordSize.value}, "${structName} stride");`);
    for (const field of collectRecordMembers(table)) {
      lines.push(`static_assert(offsetof(${structName}, ${field.memberName}) == ${field.offset}, "${structName}.${field.memberName}");`);
    }
  }
  lines.push(`static_assert(sizeof(DataTablesKnownPrefixView) == ${formatHex(prefixSize)}, "DataTables known prefix size");`);
  for (const slot of slots) {
    lines.push(`static_assert(offsetof(DataTablesKnownPrefixView, ${slot.name}) == ${formatHex(slot.offset)}, "DataTablesKnownPrefixView.${slot.name}");`);
  }
  lines.push('', '} // namespace ruffneckk::d2r33::datatables', '');
  return lines.join('\n');
}

function renderGhidraHeader(catalog, catalogHash) {
  const lines = [
    '/* Generated by scripts/reverse-engineering/d2r33-datatables-generate.mjs.',
    ' * Import with Ghidra Parse C Source. Unknown byte arrays are deliberate.',
    ' * This describes only governed fields and must not be treated as a complete SDK layout.',
    ` * Source catalog SHA-256: ${catalogHash}`,
    ' */',
    '#ifndef RUFFNECKK_D2R33_DATATABLES_GHIDRA_H',
    '#define RUFFNECKK_D2R33_DATATABLES_GHIDRA_H',
    '',
    '#include <stdint.h>',
    '',
    `#define D2R33_DATATABLES_ACCESSOR_RVA ${catalog.dataTables.accessorRva}ULL`,
    `#define D2R33_DATATABLES_CONTEXT_COUNT ${catalog.dataTables.contextCount}U`,
    `#define D2R33_DATATABLES_GLOBAL_ENTRY_STRIDE ${catalog.dataTables.globalEntryStride}U`,
    '',
    '#pragma pack(push, 1)',
  ];

  for (const table of catalog.tables) {
    const structName = `D2R33_${pascalCase(table.displayName)}RecordView`;
    const recordSize = parseHex(table.recordSize.value);
    const members = collectRecordMembers(table).map((field) => ({
      offset: field.numericOffset,
      size: field.size,
      type: field.type,
      name: field.memberName,
      status: field.status,
      evidenceIds: field.evidenceIds,
    }));
    lines.push('', `typedef struct ${structName} {`);
    lines.push(...renderMembers({ entries: members, totalSize: recordSize, typeFor: cType }));
    lines.push(`} ${structName};`);
  }

  const slots = collectSlots(catalog);
  const prefixSize = slots.at(-1).offset + slots.at(-1).size;
  const slotMembers = slots.map((slot) => ({
    offset: slot.offset,
    size: slot.size,
    type: 'uint64_t',
    name: slot.name,
    status: slot.status,
    evidenceIds: slot.evidenceIds,
  }));
  lines.push(
    '',
    '/* Known prefix only: DataTables continues beyond the last governed slot. */',
    'typedef struct D2R33_DataTablesKnownPrefixView {',
    ...renderMembers({ entries: slotMembers, totalSize: prefixSize, typeFor: cType }),
    '} D2R33_DataTablesKnownPrefixView;',
    '',
    '#pragma pack(pop)',
    '',
  );
  for (const table of catalog.tables) {
    const tableMacro = macroCase(table.id);
    lines.push(`#define D2R33_${tableMacro}_RECORD_SIZE ${table.recordSize.value}U`);
    for (const field of collectRecordMembers(table)) {
      lines.push(`#define D2R33_${tableMacro}_${macroCase(field.id)}_OFFSET ${field.offset}U`);
    }
  }
  lines.push(`#define D2R33_DATATABLES_KNOWN_PREFIX_SIZE ${formatHex(prefixSize)}U`);
  for (const slot of slots) {
    lines.push(`#define D2R33_DATATABLES_${macroCase(slot.name)}_OFFSET ${formatHex(slot.offset)}U`);
  }
  lines.push('', '#endif /* RUFFNECKK_D2R33_DATATABLES_GHIDRA_H */', '');
  return lines.join('\n');
}

function renderWitness() {
  return [
    '// Compiling this translation unit evaluates every generated static_assert.',
    '#include "d2r33_datatables_atlas.hpp"',
    '',
    'int main() {',
    '  return 0;',
    '}',
    '',
  ].join('\n');
}

function assertCatalogBytesMatch(catalog, catalogBytes) {
  const parsed = JSON.parse(Buffer.from(catalogBytes).toString('utf8'));
  if (JSON.stringify(parsed) !== JSON.stringify(catalog)) {
    throw new Error('catalogBytes do not represent the validated catalog object');
  }
}

export function buildGeneratedOutputs(catalog, catalogBytes) {
  const validation = validateCatalog(catalog);
  if (!validation.valid) {
    const first = validation.issues[0];
    throw new Error(`catalog is invalid: [${first.code}] ${first.location}: ${first.message}`);
  }
  assertCatalogBytesMatch(catalog, catalogBytes);

  const catalogHash = sha256Hex(catalogBytes);
  const generated = new Map([
    [outputNames.cppHeader, renderCppHeader(catalog, catalogHash)],
    [outputNames.ghidraHeader, renderGhidraHeader(catalog, catalogHash)],
    [outputNames.witness, renderWitness()],
  ]);
  const manifest = {
    schemaVersion: 1,
    generator: 'scripts/reverse-engineering/d2r33-datatables-generate.mjs',
    catalog: 'reverse-engineering/d2r-3.2.92777/datatables-atlas/catalog.json',
    catalogSha256: catalogHash,
    targetRuntime: catalog.targetRuntime,
    coveredBuilds: catalog.corpus.coveredBuilds.map((entry) => ({
      build: entry.build,
      status: entry.status,
    })),
    outputs: [...generated.entries()].map(([name, content]) => ({
      name,
      bytes: Buffer.byteLength(content, 'utf8'),
      sha256: sha256Hex(content),
    })),
  };
  generated.set(outputNames.manifest, `${JSON.stringify(manifest, null, 2)}\n`);
  return generated;
}

function parseArguments(args) {
  const options = {
    check: false,
    catalogPath: defaultCatalogPath,
    outputRoot: defaultGeneratedDirectory,
  };
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === '--check') {
      options.check = true;
    } else if (argument === '--catalog') {
      options.catalogPath = path.resolve(process.cwd(), args[index += 1]);
    } else if (argument === '--output-root') {
      options.outputRoot = path.resolve(process.cwd(), args[index += 1]);
    } else {
      throw new Error(`unknown argument: ${argument}`);
    }
  }
  return options;
}

function main() {
  try {
    const options = parseArguments(process.argv.slice(2));
    const catalogBytes = fs.readFileSync(options.catalogPath);
    const catalog = JSON.parse(catalogBytes.toString('utf8'));
    const generated = buildGeneratedOutputs(catalog, catalogBytes);
    if (options.check) {
      for (const [name, expected] of generated) {
        const outputPath = path.join(options.outputRoot, name);
        if (!fs.existsSync(outputPath)) throw new Error(`generated output is missing: ${outputPath}`);
        const actual = fs.readFileSync(outputPath, 'utf8');
        if (actual !== expected) throw new Error(`generated output is stale: ${outputPath}`);
      }
      console.log(`VALID generated DataTables atlas: ${path.relative(repositoryRoot, options.outputRoot)} (${generated.size} files byte-exact).`);
      return;
    }
    fs.mkdirSync(options.outputRoot, { recursive: true });
    for (const [name, content] of generated) {
      fs.writeFileSync(path.join(options.outputRoot, name), content, 'utf8');
    }
    console.log(`GENERATED DataTables atlas: ${path.relative(repositoryRoot, options.outputRoot)} (${generated.size} files).`);
  } catch (error) {
    console.error(`DataTables atlas generation failed: ${error.message}`);
    process.exitCode = 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
